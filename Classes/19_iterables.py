# An iterable is any Python object capable of returning its items one at a time in a 'for' loop.

# 1. Iterating over a List
for x in [1, 2, 3, 4]:
    print(x)

# 2. Iterating over a String (each character is an item)
for letter in "Python":
    print(letter)

# 3. Iterating over a Range object
for item in range(3):
    print(item)
