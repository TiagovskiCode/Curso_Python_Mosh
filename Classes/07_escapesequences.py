# Escape Sequences in Python
# Used to include special characters in strings using the backslash (\)

# 1. \" - Includes a double quote inside double quotes
course_name = "Python \"Programming"
print(course_name)

# 2. \' - Includes a single quote inside single quotes
message = 'It\'s a great course'
print(message)

# 3. \\ - Includes an actual backslash character
file_path = "C:\\Users\\Python"
print(file_path)

# 4. \n - Newline (moves text to the next line)
formatted_text = "First Line\nSecond Line"
print(formatted_text)

# 5. \t - Tab (adds spacing/indentation)
tabbed_text = "Name:\tTiago"
print(tabbed_text)
