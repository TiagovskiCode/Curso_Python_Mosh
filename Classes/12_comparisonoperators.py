# Comparison operators evaluate conditions and always return a boolean (True or False).

num1 = 15
num2 = 10

# 1. Equal to (==)
print(num1 == num2)  # False

# 2. Not equal to (!=)
print(num1 != num2)  # True

# 3. Greater than (>)
print(num1 > num2)   # True

# 4. Less than (<)
print(num1 < num2)   # False

# 5. Greater than or equal to (>=)
print(num1 >= num2)  # True

# 6. Less than or equal to (<=)
print(num1 <= num2)  # False
